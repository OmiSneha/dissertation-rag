import { useState, useRef, useEffect, useCallback } from 'react'
import { Upload, Send, FileText, Cpu, Database, Search, Shield, Zap, ChevronDown, X } from 'lucide-react'

const API = 'http://localhost:8000'

const THRESHOLD = 0.9

const PIPELINE_STEPS = [
  { icon: '📄', label: 'PDF text extraction' },
  { icon: '✂️', label: 'Text chunking (500 chars, 100 overlap)' },
  { icon: '🔢', label: 'Gemini embedding generation' },
  { icon: '🗄️', label: 'ChromaDB vector storage' },
  { icon: '🔍', label: 'Cosine similarity retrieval' },
  { icon: '🛡️', label: 'Retrieval-adequacy check' },
  { icon: '✨', label: 'Gemini answer generation' },
]

function Spinner() {
  return <div className="spinner" />
}

function ThinkingCard() {
  return (
    <div className="thinking-card">
      <div className="thinking-dots">
        <span /><span /><span />
      </div>
      <span className="thinking-text">Retrieving context and generating answer…</span>
    </div>
  )
}

function ChunkItem({ chunk, distance, index }) {
  const pass = distance < THRESHOLD
  return (
    <div className="chunk-item">
      <div className="chunk-header">
        <span className="chunk-num">Chunk {index + 1}</span>
        <span className={`chunk-dist ${pass ? 'pass' : 'fail'}`}>
          L2: {distance.toFixed(4)}
        </span>
        <span className="chunk-dist-label">
          {pass ? '✅ adequate' : '❌ below threshold'}
        </span>
      </div>
      <div className="chunk-body">{chunk}</div>
    </div>
  )
}

function ResultCard({ entry }) {
  const { question, result } = entry
  const [chunksOpen, setChunksOpen] = useState(false)

  return (
    <div className="result-card">
      {/* Question row */}
      <div className="result-question">
        <div className="q-avatar">Q</div>
        <p>{question}</p>
      </div>

      {/* Metrics row */}
      <div className="result-metrics">
        <div className="metric-cell">
          <span className="metric-label">Best L2 Distance</span>
          <span className={`metric-value ${result.best_distance < THRESHOLD ? 'green' : 'amber'}`}>
            {result.best_distance.toFixed(4)}
          </span>
          <span className="metric-sub">lower = more similar</span>
        </div>
        <div className="metric-cell">
          <span className="metric-label">Threshold</span>
          <span className="metric-value purple">{result.threshold}</span>
          <span className="metric-sub">adequacy cut-off</span>
        </div>
        <div className="metric-cell">
          <span className="metric-label">Evidence</span>
          <span className={`metric-value ${result.adequate ? 'green' : 'amber'}`}>
            {result.adequate ? 'Adequate' : 'Insufficient'}
          </span>
          <span className="metric-sub">{result.adequate ? 'answer generated' : 'system abstained'}</span>
        </div>
      </div>

      {/* Answer */}
      <div className="result-answer">
        <div className="answer-header">
          <span className="answer-label">Answer</span>
          <span className={`answer-status-pill ${result.adequate ? 'adequate' : 'abstained'}`}>
            {result.adequate ? 'Generated by Gemini' : 'Abstained'}
          </span>
        </div>
        {result.adequate
          ? <p className="answer-text">{result.answer}</p>
          : <p className="abstain-text">{result.answer}</p>
        }
      </div>

      {/* Chunks accordion */}
      <button className="chunks-toggle" onClick={() => setChunksOpen(o => !o)}>
        <span className={`toggle-chevron ${chunksOpen ? 'open' : ''}`}>▼</span>
        Retrieved chunks ({result.chunks.length}) — distances &amp; content
      </button>
      {chunksOpen && (
        <div className="chunks-list">
          {result.chunks.map((chunk, i) => (
            <ChunkItem key={i} chunk={chunk} distance={result.distances[i]} index={i} />
          ))}
        </div>
      )}
    </div>
  )
}

export default function App() {
  const [docState, setDocState] = useState(null)  // null | { name, numChunks, collectionName }
  const [ingesting, setIngesting] = useState(false)
  const [ingestError, setIngestError] = useState(null)
  const [dragOver, setDragOver] = useState(false)

  const [history, setHistory] = useState([])   // [{question, result}]
  const [question, setQuestion] = useState('')
  const [querying, setQuerying] = useState(false)
  const [queryError, setQueryError] = useState(null)

  const fileInputRef = useRef(null)
  const chatBottomRef = useRef(null)
  const textareaRef = useRef(null)

  useEffect(() => {
    chatBottomRef.current?.scrollIntoView({ behavior: 'smooth' })
  }, [history, querying])

  const handleFile = useCallback(async (file) => {
    if (!file || !file.name.toLowerCase().endsWith('.pdf')) {
      setIngestError('Please upload a PDF file.')
      return
    }
    setIngestError(null)
    setIngesting(true)
    setDocState(null)
    setHistory([])

    try {
      const form = new FormData()
      form.append('file', file)
      const res = await fetch(`${API}/ingest`, { method: 'POST', body: form })
      if (!res.ok) {
        const err = await res.json()
        throw new Error(err.detail || 'Ingestion failed')
      }
      const data = await res.json()
      setDocState({
        name: file.name,
        numChunks: data.num_chunks,
        collectionName: data.collection_name,
      })
    } catch (e) {
      setIngestError(e.message)
    } finally {
      setIngesting(false)
    }
  }, [])

  const handleDrop = useCallback((e) => {
    e.preventDefault()
    setDragOver(false)
    const file = e.dataTransfer.files[0]
    handleFile(file)
  }, [handleFile])

  const handleSend = async () => {
    const q = question.trim()
    if (!q || !docState || querying) return
    setQuestion('')
    setQueryError(null)
    setQuerying(true)

    try {
      const res = await fetch(`${API}/query`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ question: q, collection_name: docState.collectionName }),
      })
      if (!res.ok) {
        const err = await res.json()
        throw new Error(err.detail || 'Query failed')
      }
      const data = await res.json()
      setHistory(h => [...h, { question: q, result: data }])
    } catch (e) {
      setQueryError(e.message)
    } finally {
      setQuerying(false)
    }
  }

  const handleKeyDown = (e) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault()
      handleSend()
    }
  }

  const activeStep = ingesting ? 2 : docState ? 4 : -1

  return (
    <div className="layout">
      {/* ── Top bar ── */}
      <header className="topbar">
        <div className="topbar-logo">
          <div className="topbar-logo-icon">📄</div>
          <span className="topbar-title">RAG Pipeline</span>
          <span className="topbar-badge">Mid-Semester Demo</span>
        </div>
        <span className="topbar-sub">
          Hallucination Detection in Retrieval-Augmented Document Q&amp;A · BITS Pilani WILP 2026
        </span>
      </header>

      {/* ── Sidebar ── */}
      <aside className="sidebar">

        {/* Upload */}
        <div>
          <p className="sidebar-section-label">Document</p>

          {!docState && !ingesting && (
            <label
              className={`upload-card ${dragOver ? 'drag-over' : ''}`}
              onDragOver={e => { e.preventDefault(); setDragOver(true) }}
              onDragLeave={() => setDragOver(false)}
              onDrop={handleDrop}
            >
              <input
                ref={fileInputRef}
                type="file"
                accept=".pdf"
                onChange={e => handleFile(e.target.files[0])}
              />
              <div className="upload-icon">📤</div>
              <p>Drop a PDF here or click to browse</p>
              <small>PDF only</small>
            </label>
          )}

          {ingesting && (
            <div className="spinner-row">
              <Spinner />
              <span>Ingesting document…</span>
            </div>
          )}

          {docState && (
            <div className="doc-pill">
              <span className="doc-pill-name">📄 {docState.name}</span>
              <span className="doc-pill-meta">{docState.numChunks} chunks · ChromaDB ✓</span>
              <button className="doc-pill-clear" onClick={() => { setDocState(null); setHistory([]); setQueryError(null) }}>
                × Remove document
              </button>
            </div>
          )}

          {ingestError && <p style={{ fontSize: 12, color: 'var(--red)', marginTop: 8 }}>{ingestError}</p>}
        </div>

        {/* Pipeline steps */}
        <div>
          <p className="sidebar-section-label">Pipeline</p>
          <div className="steps-list">
            {PIPELINE_STEPS.map((s, i) => (
              <div key={i} className="step-item">
                <div className={`step-dot ${i < activeStep ? 'done' : i === activeStep ? 'active' : ''}`} />
                <span className="step-text">
                  <strong>{s.icon} </strong>{s.label}
                </span>
              </div>
            ))}
          </div>
        </div>

        {/* Config */}
        <div>
          <p className="sidebar-section-label">Configuration</p>
          <table className="config-table">
            <tbody>
              <tr><td>Embed model</td><td>gemini-embedding-001</td></tr>
              <tr><td>Gen model</td><td>gemini-3.8-flash</td></tr>
              <tr><td>Chunk size</td><td>500 chars</td></tr>
              <tr><td>Overlap</td><td>100 chars</td></tr>
              <tr><td>Top-K</td><td>3 chunks</td></tr>
              <tr><td>Threshold (L2)</td><td style={{ color: 'var(--accent)' }}>{THRESHOLD}</td></tr>
            </tbody>
          </table>
        </div>

        {/* Dataset */}
        <div>
          <p className="sidebar-section-label">Benchmark Dataset</p>
          <div className="dataset-badge">
            <strong>RAGTruth QA Subset</strong><br />
            Human-annotated question–context–answer triples. Binary hallucination labels will be derived from existing annotations in the classifier experiments (future work).
          </div>
        </div>

      </aside>

      {/* ── Main ── */}
      <main className="main">
        {!docState && !ingesting ? (
          <div className="empty-state">
            <div className="empty-icon">💬</div>
            <h2>Upload a document to begin</h2>
            <p>Drop a PDF in the sidebar. The pipeline will extract, chunk, embed, and index it — then you can ask questions.</p>
          </div>
        ) : (
          <>
            <div className="chat-area">
              {history.length === 0 && docState && !querying && (
                <div className="empty-state" style={{ flex: 'none', paddingTop: 40 }}>
                  <div className="empty-icon">🔍</div>
                  <h2>Document ready</h2>
                  <p>Ask anything about <strong>{docState.name}</strong> using the input below.</p>
                </div>
              )}

              {history.map((entry, i) => (
                <ResultCard key={i} entry={entry} />
              ))}

              {querying && <ThinkingCard />}
              {queryError && <div className="error-card">❌ {queryError}</div>}

              <div ref={chatBottomRef} />
            </div>

            <div className="input-bar">
              <textarea
                ref={textareaRef}
                rows={1}
                placeholder={docState ? 'Ask a question about your document… (Enter to send)' : 'Ingesting document…'}
                value={question}
                disabled={!docState || querying}
                onChange={e => setQuestion(e.target.value)}
                onKeyDown={handleKeyDown}
                onInput={e => {
                  e.target.style.height = 'auto'
                  e.target.style.height = Math.min(e.target.scrollHeight, 120) + 'px'
                }}
              />
              <button
                className="send-btn"
                disabled={!question.trim() || !docState || querying}
                onClick={handleSend}
                title="Send (Enter)"
              >
                <Send size={18} />
              </button>
            </div>
          </>
        )}
      </main>
    </div>
  )
}
